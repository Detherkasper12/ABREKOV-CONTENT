// Writes supabase/seed.sql with the first two resources (5 Claude Skills, CLAUDE.md template).
//   node scripts/seed.mjs            → regenerate supabase/seed.sql (paste it into the Supabase SQL Editor)
//   node --env-file=.env.local scripts/seed.mjs --apply   → also run it against DATABASE_URL
// Safe to re-run: existing slugs are left untouched.
import { readFileSync, writeFileSync } from "node:fs";
import { claudeMd, claudeSkills, claudeVideoEditing } from "../seed/resources.mjs";

const template = readFileSync(new URL("../seed/CLAUDE.md", import.meta.url), "utf8");
// The template ships as a static file in public/downloads, so it needs no Storage upload.
const resources = [claudeSkills, claudeMd(template, "/downloads/CLAUDE.md", Buffer.byteLength(template))];

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sqlText =
  "-- Generated by scripts/seed.mjs. Run after migrations/0001_init.sql.\n" +
  resources
    .map(
      (r) => `insert into resources (slug, title, description, label, keyword, category, tags, kind, featured, status, published_at, blocks)
values (${q(r.slug)}, ${q(r.title)}, ${q(r.description)}, ${q(r.label)}, ${q(r.keyword)}, ${q(r.category)},
  array[${r.tags.map(q).join(", ")}]::text[], ${q(r.kind)}, ${r.featured}, 'published', now(),
  ${q(JSON.stringify(r.blocks))}::jsonb)
on conflict (slug) do nothing;`,
    )
    .join("\n\n") +
  "\n";

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sqlText);
console.log("wrote supabase/seed.sql");

// The link-only video-editing guide: its own file, so it can be added to a live database without
// touching the first two. Applies migration 0003 first because the insert uses the unlisted column.
const g = claudeVideoEditing;
const guideSql = `-- Generated by scripts/seed.mjs. Adds the link-only guide "${g.slug}". Safe to re-run.
alter table resources add column if not exists unlisted boolean not null default false;

insert into resources (slug, title, description, label, keyword, category, tags, kind, featured, unlisted, status, published_at, blocks)
values (${q(g.slug)}, ${q(g.title)}, ${q(g.description)}, ${q(g.label)}, ${q(g.keyword)}, ${q(g.category)},
  array[${g.tags.map(q).join(", ")}]::text[], ${q(g.kind)}, ${g.featured}, ${g.unlisted}, 'published', now(),
  ${q(JSON.stringify(g.blocks))}::jsonb)
on conflict (slug) do nothing;
`;
writeFileSync(new URL("../supabase/seed-claude-video-editing.sql", import.meta.url), guideSql);
console.log("wrote supabase/seed-claude-video-editing.sql");

if (process.argv.includes("--apply")) {
  const { default: postgres } = await import("postgres");
  const sql = postgres(process.env.DATABASE_URL || process.env.POSTGRES_URL, { prepare: false, max: 1 });
  await sql.unsafe(sqlText);
  await sql.unsafe(guideSql);
  await sql.end();
  console.log("applied to DATABASE_URL");
}
